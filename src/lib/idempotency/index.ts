// ══════════════════════════════════════════════════════════════
//  Generic idempotency guard
//
//  Prevents duplicate records caused by retries, refreshes, or
//  double-clicks. The client sends a `clientRequestId` with each
//  POST; the server checks for an existing record with the same ID
//  in the same collection. If found, returns the original.
//
//  This library depends only on db.ts and cuid2 — it is fully
//  domain-agnostic and reusable by every module with POST endpoints.
//  No entity names or collection names are hardcoded; all are
//  passed as parameters by the caller.
// ══════════════════════════════════════════════════════════════

import { createId } from '@paralleldrive/cuid2';
import { findWhere } from '@/lib/db';

// ─────────────────────────────────────────────────────────────
//  Result types
// ─────────────────────────────────────────────────────────────

/**
 * Result when no duplicate was found — safe to proceed.
 */
export interface IdempotencyClear {
  /** No duplicate found. */
  isDuplicate: false;
  existing: null;
}

/**
 * Result when a duplicate was found — return the existing record.
 */
export interface IdempotencyDuplicate<T = Record<string, unknown>> {
  /** Duplicate found. */
  isDuplicate: true;
  existing: T;
}

/**
 * Result of an idempotency check. Discriminate on `isDuplicate`.
 */
export type IdempotencyCheckResult<T = Record<string, unknown>> =
  | IdempotencyClear
  | IdempotencyDuplicate<T>;

// ─────────────────────────────────────────────────────────────
//  Request window generation
// ─────────────────────────────────────────────────────────────

/**
 * A client request window generated by the client before a POST.
 * Contains the idempotency key and an optional expiry timestamp.
 */
export interface ClientRequestWindow {
  /** Unique idempotency key generated by the client (cuid2). */
  clientRequestId: string;
  /** Optional ISO 8601 expiry timestamp. null if no expiry. */
  expiresAt: string | null;
}

/**
 * Default dedup window duration in milliseconds (30 minutes).
 */
const DEFAULT_WINDOW_MS = 30 * 60 * 1000;

/**
 * Generate a client request window for idempotent POST requests.
 *
 * The caller (typically a frontend utility) calls this before each POST
 * and sends `clientRequestId` + `expiresAt` in the request body.
 * The server-side {@link dedupByClientRequest} checks for an existing
 * record with the same key.
 *
 * @param durationMs - How long the dedup window lasts in ms (defaults to 30 min).
 * @returns A {@link ClientRequestWindow} with a fresh cuid2 key and an expiry.
 *
 * @remarks
 * Side effects: none. This is a pure function (cuid2 is deterministic).
 *
 * @example
 * ```ts
 * // Frontend before POST:
 * const window = generateRequestWindow();
 * await fetch('/api/quality-observations', {
 *   method: 'POST',
 *   body: JSON.stringify({ ...data, clientRequestId: window.clientRequestId }),
 * });
 * ```
 */
export function generateRequestWindow(durationMs: number = DEFAULT_WINDOW_MS): ClientRequestWindow {
  return {
    clientRequestId: createId(),
    expiresAt: new Date(Date.now() + durationMs).toISOString(),
  };
}

// ─────────────────────────────────────────────────────────────
//  Dedup check
// ─────────────────────────────────────────────────────────────

/**
 * Check whether a record with the given `clientRequestId` already
 * exists in the specified collection. This is the stable public API
 * for idempotency; the old name `checkForDuplicate` is preserved as
 * an alias for backward compatibility.
 *
 * Uses the cached getAll for cheap repeated calls. Returns the
 * existing record if a duplicate is found, so the caller can return
 * it to the client (transparent idempotency).
 *
 * @param collection      - RTDB collection name to check.
 * @param clientRequestId - The idempotency key from the client.
 * @returns {@link IdempotencyClear} if no duplicate, otherwise
 *          {@link IdempotencyDuplicate} with the existing record.
 *
 * @remarks
 * Side effects: reads from the RTDB (cached).
 */
export async function dedupByClientRequest<T = Record<string, unknown>>(
  collection: string,
  clientRequestId: string,
): Promise<IdempotencyCheckResult<T>> {
  if (!clientRequestId) {
    return { isDuplicate: false, existing: null };
  }

  const existing = await findWhere<T & { clientRequestId?: string }>(
    collection,
    { clientRequestId },
  );

  if (existing.length > 0) {
    // Return the first match (should be exactly one by design).
    return { isDuplicate: true, existing: existing[0] as T };
  }

  return { isDuplicate: false, existing: null };
}

/**
 * @deprecated Use {@link dedupByClientRequest} instead.
 * Kept as a backward-compatible alias.
 */
export const checkForDuplicate = dedupByClientRequest;
